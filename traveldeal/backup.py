"""Nightly logical backup of all user data.

Why this exists: the Always Free Autonomous Database has no backup or restore,
and it is stopped after 7 days without SQL activity. This job fixes both:
it reads every table (which counts as activity) and writes a gzipped JSON
snapshot to OCI Object Storage, where a lifecycle rule keeps 30 days.

    python -m traveldeal.backup                  # back up to Object Storage (on the VM)
    python -m traveldeal.backup --local out.json.gz
    python -m traveldeal.backup --restore out.json.gz   # into an EMPTY database
"""

from __future__ import annotations

import argparse
import gzip
import json
import sys
from datetime import date, datetime, timezone
from decimal import Decimal
from pathlib import Path
from typing import Any

from sqlalchemy import Engine, inspect, select

from .config import get_settings
from .db import AppUser, Base, SavedComparison, UserSettingsRow, WalletCard, init_db, make_engine

# Parent tables first so a restore satisfies foreign keys.
TABLES = [AppUser.__table__, WalletCard.__table__, UserSettingsRow.__table__, SavedComparison.__table__]


def _jsonable(v: Any) -> Any:
    if isinstance(v, (datetime, date)):
        return v.isoformat()
    if isinstance(v, Decimal):
        return float(v)
    return v


def snapshot(engine: Engine) -> dict[str, Any]:
    out: dict[str, Any] = {"format": 1, "created_at": datetime.now(timezone.utc).isoformat(), "tables": {}}
    with engine.connect() as conn:
        for table in TABLES:
            rows = conn.execute(select(table)).mappings().all()
            out["tables"][table.name] = [{k: _jsonable(v) for k, v in r.items()} for r in rows]
    return out


def restore(engine: Engine, data: dict[str, Any]) -> dict[str, int]:
    """Load a snapshot into an empty database. Refuses to overwrite existing users."""
    init_db(engine)
    counts = {}
    with engine.begin() as conn:
        if conn.execute(select(AppUser.id).limit(1)).first() is not None:
            raise RuntimeError("Target database already has users; restore only into an empty database.")
        for table in TABLES:
            rows = data["tables"].get(table.name, [])
            datetime_cols = {c.name for c in table.columns if c.type.python_type is datetime}
            for r in rows:
                for col in datetime_cols & r.keys():
                    r[col] = datetime.fromisoformat(r[col]) if r[col] else None
            if rows:
                conn.execute(table.insert(), rows)
            counts[table.name] = len(rows)
        if engine.dialect.name == "oracle":
            # Explicit ids were inserted, so move each identity sequence past the highest id.
            for table in TABLES:
                if "id" in table.columns and table.c.id.identity is not None:
                    conn.exec_driver_sql(
                        f"ALTER TABLE {table.name} MODIFY id GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE)"
                    )
    return counts


def upload_to_object_storage(payload: bytes, bucket: str, object_name: str) -> None:
    """Upload using the VM's instance principal: no API keys stored on the server."""
    import oci  # imported lazily so local development doesn't need the OCI SDK

    signer = oci.auth.signers.InstancePrincipalsSecurityTokenSigner()
    client = oci.object_storage.ObjectStorageClient(config={}, signer=signer)
    namespace = client.get_namespace().data
    client.put_object(namespace, bucket, object_name, payload, content_type="application/gzip")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--local", type=Path, help="write the snapshot to this file instead of Object Storage")
    parser.add_argument("--restore", type=Path, help="restore a snapshot file into an empty database")
    args = parser.parse_args(argv)

    settings = get_settings()
    engine = make_engine(settings)

    if args.restore:
        data = json.loads(gzip.decompress(args.restore.read_bytes()))
        print(json.dumps(restore(engine, data)))
        return 0

    init_db(engine)
    missing = [t.name for t in TABLES if not inspect(engine).has_table(t.name)]
    if missing:
        print(f"Tables missing: {missing}", file=sys.stderr)
        return 1
    data = snapshot(engine)
    payload = gzip.compress(json.dumps(data, separators=(",", ":")).encode())
    counts = {name: len(rows) for name, rows in data["tables"].items()}

    if args.local:
        args.local.write_bytes(payload)
        print(f"Wrote {args.local} ({len(payload):,} bytes) {counts}")
        return 0
    if not settings.backup_bucket:
        print("BACKUP_BUCKET is not set; use --local for a file backup.", file=sys.stderr)
        return 1
    name = f"{settings.backup_prefix}/{date.today().isoformat()}.json.gz"
    upload_to_object_storage(payload, settings.backup_bucket, name)
    print(f"Uploaded {name} ({len(payload):,} bytes) {counts}")
    return 0


__all__ = ["snapshot", "restore", "Base"]

if __name__ == "__main__":
    raise SystemExit(main())
